"""Generate docs/sample_traces_and_audit.md from a REAL run (temporary database, offline mock provider unless --provider groq).
Nothing in the output is hand-written: it is what the application recorded."""
import argparse
import json
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from app import config, db

ap = argparse.ArgumentParser(); ap.add_argument("--provider", choices=["mock", "groq"], default="mock"); a = ap.parse_args()
config.LLM_PROVIDER = a.provider
ok, why = config.llm_configured()
if not ok:
    sys.exit(f"Cannot run: {why}")
config.ENV, config.IS_DEV, config.SESSION_COOKIE_SECURE, config.DEMO_TODAY = "test", True, False, config.DEMO_TODAY or "2026-10-30"
config.PASSWORD_HASH_METHOD = "pbkdf2:sha256:1000"
with tempfile.TemporaryDirectory() as tmp:
    url = f"sqlite:///{Path(tmp) / 's.db'}"; config.DATABASE_URL = url
    from scripts.init_db import upgrade
    upgrade(url); db.init_engine(url)
    from app.services.ingest_service import ingest_policy
    from app.services.seed_service import DEMO_PASSWORDS, seed_demo_data
    with db.session_scope() as s:
        seed_demo_data(s); ingest_policy(s)
    from fastapi.testclient import TestClient
    from sqlalchemy import select
    from app.main import app
    from app.models import AuditEvent, AgentTrace
    from app.services import audit_service, trace_service

    def login(u):
        c = TestClient(app); r = c.post("/api/auth/login", json={"username": u, "password": DEMO_PASSWORDS[u]}); c.headers["X-CSRF-Token"] = r.json()["user"]["csrf_token"]; return c
    stu, staff = login("S2025AI001"), login("program.office")
    def chat(t, cid=None):
        return stu.post("/api/chat", json={"message": t, **({"conversation_id": cid} if cid else {})}).json()
    j1 = chat("What is my current fee status?")
    j2 = chat("Show me the fee status of S2025AI002")
    j3 = chat("My OTP is 482913")
    j4 = chat("Change my mobile number to +91 91234 56789"); j5 = chat("yes", j4["conversation_id"]); n = j5["approvals"][0]["request_number"]
    appr = staff.post(f"/api/approvals/{n}/approve", json={"comment": "verified by phone"}).json()["approval"]
    with db.session_scope() as s:
        def trace(tid):
            return trace_service.to_dict(s.execute(select(AgentTrace).where(AgentTrace.trace_id == tid)).scalar_one())
        def audit(**f):
            q = select(AuditEvent)
            for k, v in f.items(): q = q.where(getattr(AuditEvent, k) == v)
            return [audit_service.to_dict(e) for e in s.execute(q.order_by(AuditEvent.id)).scalars()]
        out = ["# Sample traces and audit records", "",
               f"Generated by `python scripts/export_samples.py` from a real run (provider `{config.LLM_PROVIDER}`; temporary database; fictional data). Nothing here is hand-written.",
               "With the offline mock provider the token counts are local estimates (the trace labels them), so they are illustrative of the format, not of real usage.", ""]
        def block(title, obj, note=""):
            out.extend([f"## {title}", note, "```json", json.dumps(obj, indent=2, ensure_ascii=False), "```", ""])
        block("1. Agent trace: own fee status (a tool is called under the student's identity)", trace(j1["trace"]["trace_id"]), "One row in `agent_traces`. `tools_used[].arguments` are redacted before storage.")
        block("2. Agent trace: another student's record requested (blocked by the backend)", trace(j2["trace"]["trace_id"]), "The tool returned FORBIDDEN; the other student's data never reached the model.")
        block("3. Audit: the denied attempt (no private content, same trace ID)", audit(event_type="ACCESS_DENIED", trace_id=j2["trace"]["trace_id"]))
        block("4. Audit: a secret shared in chat (masked, not stored; only the label is recorded)", audit(event_type="SECRET_SHARED"), "The OTP digits appear nowhere in this record, the conversation, the trace or memory.")
        block("5. Approval request after the student confirmed (nothing has been applied yet)", j5["approvals"][0])
        block("6. Approval after the staff decision (executed exactly once)", appr)
        block("7. Audit trail of the whole approval (note: field NAMES only, never the new phone number)", [e for e in audit() if (e.get("details") or {}).get("request_number") == n or e["event_type"] == "SENSITIVE_REQUEST"])
        db.engine.dispose()
Path(config.ROOT / "docs").mkdir(exist_ok=True)
(config.ROOT / "docs" / "sample_traces_and_audit.md").write_text("\n".join(out), encoding="utf-8")
print("wrote docs/sample_traces_and_audit.md,", len("\n".join(out)), "characters")
